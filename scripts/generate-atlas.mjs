async function createDomain(domain) {
  const domainDir = path.join(contentRoot, domain.slug)
  const meta = {
    index: metaEntry('Overview', { theme: { toc: true } })
  }

  await writeIfMissing(
    path.join(domainDir, 'index.mdx'),
    document({
      title: domain.title,
      description: domain.description,
      domain: domain.title,
      category: domain.title,
      subcategory: '',
      difficulty: taxonomy.project.defaultDifficulty,
      stage: 'orientation',
      type: 'domain',
      status: 'scaffold',
      tags: [domain.slug],
      prerequisites: [],
      related: [],
      researchQuestions: [],
      asIndexPage: true
    })
  )

  for (const topic of domain.children) {
    meta[topic.slug] = metaEntry(topic.title)
    await createTopic(domain, topic, domainDir)
  }

  await writeGenerated(path.join(domainDir, '_meta.js'), metaFile(meta))
}

async function createTopic(domain, topic, domainDir) {
  const topicDir = path.join(domainDir, topic.slug)
  const meta = {
    index: metaEntry('Overview'),
    roadmap: metaEntry('Roadmap')
  }

  await writeIfMissing(
    path.join(topicDir, 'index.mdx'),
    document(
      topicMetadata(domain, topic, {
        title: topic.title,
        description: topic.description ?? `Placeholder scaffold for ${topic.title}.`,
        type: 'topic-index',
        stage: 'orientation',
        asIndexPage: true
      })
    )
  )

  await writeIfMissing(
    path.join(topicDir, 'roadmap.mdx'),
    document(
      topicMetadata(domain, topic, {
        title: `${topic.title} Roadmap`,
        description: `Roadmap placeholder for sequencing ${topic.title} learning and research work.`,
        type: 'roadmap',
        stage: 'foundation',
        tags: [domain.slug, topic.slug, 'roadmap']
      })
    )
  )

  if (Array.isArray(topic.track)) {
    for (const [index, item] of topic.track.entries()) {
      meta[item.slug] = metaEntry(item.title)
      const related = []
      if (topic.track[index - 1]) related.push(`./${topic.track[index - 1].slug}`)
      if (topic.track[index + 1]) related.push(`./${topic.track[index + 1].slug}`)

      await writeIfMissing(
        path.join(topicDir, `${item.slug}.mdx`),
        document(
          topicMetadata(domain, topic, {
            title: item.title,
            description: `Placeholder scaffold for ${item.title} in the ${topic.title} learning track.`,
            subcategory: topic.title,
            type: 'track-topic',
            difficulty: trackDifficulty(index),
            stage: trackStage(index),
            tags: [domain.slug, topic.slug, item.slug.replace(/^\d+-/, '')],
            related
          })
        )
      )
    }
  }

  await writeGenerated(path.join(topicDir, '_meta.js'), metaFile(meta))
}

async function createRootMeta() {
  const meta = {
    index: metaEntry('Atlas', { type: 'page' })
  }

  for (const domain of taxonomy.domains) {
    meta[domain.slug] = metaEntry(domain.title, { type: 'page' })
  }

  await writeGenerated(path.join(contentRoot, '_meta.js'), metaFile(meta))
}

await createHome()
await createRootMeta()

for (const domain of taxonomy.domains) {
  await createDomain(domain)
}

console.log(`Generated atlas scaffold for ${taxonomy.domains.length} domains.`)
