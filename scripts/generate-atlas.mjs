import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { existsSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const taxonomyPath = path.join(root, 'atlas', 'taxonomy.json')
const contentRoot = path.join(root, 'content')

const taxonomy = JSON.parse(await readFile(taxonomyPath, 'utf8'))
const generatedNotice = '// Generated by scripts/generate-atlas.mjs. Edit atlas/taxonomy.json instead.\n'

function titleCase(slug) {
  return slug
    .split('-')
    .map(part => part.charAt(0).toUpperCase() + part.slice(1))
    .join(' ')
}

function quoteYaml(value) {
  return `"${String(value).replaceAll('\\', '\\\\').replaceAll('"', '\\"')}"`
}

function yamlArray(values) {
  if (!values || values.length === 0) {
    return ' []'
  }

  return `\n${values.map(value => `  - ${quoteYaml(value)}`).join('\n')}`
}

function trackStage(index) {
  if (index <= 9) return 'foundation'
  if (index <= 19) return 'practice'
  if (index <= 31) return 'internals'
  if (index <= 39) return 'systems'
  return 'research'
}

function trackDifficulty(index) {
  if (index <= 9) return 'beginner'
  if (index <= 25) return 'intermediate'
  if (index <= 39) return 'advanced'
  return 'research'
}

function frontmatter(metadata) {
  return [
    '---',
    `title: ${quoteYaml(metadata.title)}`,
    `description: ${quoteYaml(metadata.description)}`,
    `domain: ${quoteYaml(metadata.domain)}`,
    `category: ${quoteYaml(metadata.category)}`,
    `subcategory: ${quoteYaml(metadata.subcategory ?? '')}`,
    `difficulty: ${quoteYaml(metadata.difficulty)}`,
    `stage: ${quoteYaml(metadata.stage)}`,
    `type: ${quoteYaml(metadata.type)}`,
    `status: ${quoteYaml(metadata.status)}`,
    `tags:${yamlArray(metadata.tags)}`,
    `prerequisites:${yamlArray(metadata.prerequisites)}`,
    `related:${yamlArray(metadata.related)}`,
    `researchQuestions:${yamlArray(metadata.researchQuestions)}`,
    metadata.asIndexPage ? 'asIndexPage: true' : null,
    '---'
  ]
    .filter(Boolean)
    .join('\n')
}

function placeholderBody(title) {
  const sections = taxonomy.requiredSections
    .map(section => `## ${section}\n\n<!-- Content will be written manually. -->`)
    .join('\n\n')

  return `# ${title}\n\n> Scaffold status: this page defines structure only. Replace comments with manually researched content when the topic is ready.\n\n${sections}\n`
}

function document(metadata) {
  return `${frontmatter(metadata)}\n\n${placeholderBody(metadata.title)}`
}

async function writeIfMissing(filePath, contents) {
  await mkdir(path.dirname(filePath), { recursive: true })
  if (!existsSync(filePath)) {
    await writeFile(filePath, contents, 'utf8')
  }
}

async function writeGenerated(filePath, contents) {
  await mkdir(path.dirname(filePath), { recursive: true })
  await writeFile(filePath, contents, 'utf8')
}

function metaFile(record) {
  return `${generatedNotice}export default ${JSON.stringify(record, null, 2)}\n`
}

function metaEntry(title, extra = {}) {
  return {
    title,
    ...extra,
    theme: {
      ...(extra.theme ?? {}),
      timestamp: false
    }
  }
}

function topicMetadata(domain, topic, overrides = {}) {
  return {
    title: overrides.title ?? topic.title,
    description:
      overrides.description ??
      `Placeholder scaffold for ${topic.title} inside ${domain.title}.`,
    domain: domain.title,
    category: topic.title,
    subcategory: overrides.subcategory ?? '',
    difficulty: overrides.difficulty ?? taxonomy.project.defaultDifficulty,
    stage: overrides.stage ?? taxonomy.project.defaultStage,
    type: overrides.type ?? 'topic',
    status: 'scaffold',
    tags: overrides.tags ?? [domain.slug, topic.slug],
    prerequisites: overrides.prerequisites ?? [],
    related: overrides.related ?? [],
    researchQuestions: overrides.researchQuestions ?? [],
    asIndexPage: overrides.asIndexPage ?? false
  }
}

